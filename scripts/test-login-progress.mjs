import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('index.html','utf8'),css=fs.readFileSync('assets/css/app.css','utf8'),js=fs.readFileSync('assets/js/app.js','utf8');
const loginStart=js.indexOf('async function login(e){'),loginEnd=js.indexOf('\nasync function toggleRMAdminMode(',loginStart);
assert.ok(loginStart>=0&&loginEnd>loginStart,'Login handler missing');
const handler=js.slice(loginStart,loginEnd);
assert.ok(html.includes('id="loginProgressTitle"')&&html.includes('id="loginProgressText"'),'Login step labels are required');
assert.ok(html.includes('class="login-progress-logo"'),'Rotating login logo');
assert.ok(css.includes('#loginView #loginProgress{')&&css.includes('position:absolute;inset:0'),'Progress must be centered inside login card');
assert.ok(css.includes('body:has(#loginView:not(.hidden)) #globalBusy{display:none!important}'),'General app loader must not overlay login');
assert.ok(!css.includes('body:has(#appShell:not(.hidden)) #globalBusy{display:none'),'Do not hide in-app loading');
assert.ok(handler.includes("setLoginProgress('Verifica delle credenziali…'"),'Authentication phase');
assert.ok(handler.includes("setLoginProgress('Accesso riuscito'"),'Authentication success phase');
assert.ok(handler.includes("setLoginProgress('Caricamento dati…'"),'Data loading phase');
assert.ok(handler.includes("setLoginProgress('Apertura AGENDA DM…'"),'App opening phase');
assert.ok(handler.includes("}finally{progress.classList.add('hidden');btn.disabled=false;btn.textContent='Accedi'}}"),'Progress must always dismiss');
const start=js.indexOf('function setLoginProgress('),end=js.indexOf('\nasync function login(e){',start);
assert.ok(start>=0&&end>start,'Progress helper missing');
const nodes=new Map();for(const id of ['loginProgress','loginProgressTitle','loginProgressText'])nodes.set(id,{classList:{remove(v){this.hidden=v!=='hidden'},add(v){this.hidden=v==='hidden'}},textContent:''});
const context={$:sel=>nodes.get(sel.slice(1))};vm.createContext(context);
vm.runInContext(js.slice(start,end)+';this.fn=setLoginProgress;',context);
context.fn('Verifica delle credenziali…','Controllo ID e password.');
assert.equal(nodes.get('loginProgressTitle').textContent,'Verifica delle credenziali…');
assert.equal(nodes.get('loginProgressText').textContent,'Controllo ID e password.');
assert.equal(nodes.get('loginProgress').classList.hidden,false);
console.log('PASS: login progress phases, placement, cleanup and app-loader isolation');
